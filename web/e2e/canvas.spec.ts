test("neutral loading border tracks only pending charts and honors reduced motion", async ({page}) => {
  await seedWorkspace(page, [{path: "/progress/loss", size: "normal"}]);
  await mockApi(page);
  let release = () => {};
  const pending = new Promise<void>(resolve => {release = resolve;});
  await page.emulateMedia({reducedMotion: "no-preference"});
  await page.route("**/api/snapshots/query", async route => {await pending; await route.fallback();});
  await page.goto("/rvx?runs=run-1");
  const chart = page.locator(".chart-card").first();
  try {
    await expect(chart).toHaveAttribute("data-refreshing", "true");
    await expect(chart).toHaveCSS("animation-name", "chart-refresh");
    await page.emulateMedia({reducedMotion: "reduce"});
    await expect(chart).toHaveCSS("animation-name", "none");
    release();
    await expect(chart.locator("canvas")).toBeVisible();
    await expect(chart).toHaveAttribute("data-refreshing", "false");
  } finally {
    release();
  }
});

test("Live pauses polling without remounting charts and manual refresh remains available", async ({page}) => {
  await page.clock.install();
  await seedWorkspace(page, [{path: "/progress/loss", size: "normal"}]);
  const requests = await mockApi(page);
  await page.goto("/rvx?runs=run-1");
  const chart = page.locator(".chart-card").first();
  await expect(chart.locator("canvas")).toBeVisible();
  const canvas = await chart.locator("canvas").elementHandle();
  const live = page.getByRole("button", {name: "Live", exact: true});
  await live.click();
  await expect(live).toHaveAttribute("aria-pressed", "false");
  const catalogReads = () => requests.filter(request => request.path === "/api/charts/catalog").length;
  const paused = catalogReads();
  await page.clock.fastForward(12_000);
  expect(catalogReads()).toBe(paused);
  await page.getByRole("button", {name: "Refresh runs", exact: true}).click();
  await expect.poll(catalogReads).toBeGreaterThan(paused);
  await live.click();
  await expect(live).toHaveAttribute("aria-pressed", "true");
  const resumed = catalogReads();
  await page.clock.fastForward(6_000);
  await expect.poll(catalogReads).toBeGreaterThan(resumed);
  expect(await canvas!.evaluate(element => element.isConnected)).toBe(true);
});
