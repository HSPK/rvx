import {test, expect} from "@playwright/test";
import {mockApi, seedUiState, seedWorkspace, setTheme} from "./fixtures";

test("canvas panels retain charts, selection and independent desktop/mobile collapse states", async ({page}) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const requests = await mockApi(page);
  await page.goto("/rvx?runs=run-1,run-2");
  const chart = page.locator(".chart-card").first();
  await expect(chart.locator("canvas")).toBeVisible();
  const canvas = await chart.locator("canvas").elementHandle();
  const before = (await chart.boundingBox())!.width;
  const reads = requests.filter(request => request.path === "/api/snapshots/query").length;
  const collapse = page.getByRole("button", {name: "Collapse Runs panel", exact: true});
  const bounds = (await collapse.boundingBox())!;
  await collapse.click();
  const expand = page.getByRole("button", {name: "Expand Runs panel", exact: true});
  await expect(page.locator(".runs-dock")).toHaveCSS("width", "64px");
  expect((await expand.boundingBox())!.width).toBe(bounds.width);
  expect((await expand.boundingBox())!.height).toBe(bounds.height);
  expect((await expand.boundingBox())!.y).toBe(bounds.y);
  await expect(page.getByRole("searchbox", {name: "Search runs"})).not.toBeVisible();
  await expect(page.getByRole("checkbox", {name: "Select grpo · baseline", exact: true})).toBeChecked();
  await expect.poll(async () => (await chart.boundingBox())!.width).toBeGreaterThan(before);
  expect(await canvas!.evaluate(element => element.isConnected)).toBe(true);
  expect(requests.filter(request => request.path === "/api/snapshots/query").length).toBe(reads);
  await page.reload();
  await expect(expand).toBeVisible();
  await page.setViewportSize({width: 390, height: 844});
  await expect(page.locator(".runs-dock")).toBeVisible();
  await expect(page.getByRole("searchbox", {name: "Search runs"})).not.toBeVisible();
  const manage = page.getByRole("button", {name: "Manage runs", exact: true});
  await expect(manage).toHaveAttribute("aria-expanded", "false");
  expect((await page.locator(".runs-dock").boundingBox())!.height).toBeLessThan(200);
  await manage.click();
  await expect(page.getByRole("combobox", {name: "Project", exact: true})).toBeVisible();
  await expect(page.getByRole("button", {name: "Run details for grpo · warm-start", exact: true})).toBeVisible();
  await page.reload();
  await expect(manage).toHaveAttribute("aria-expanded", "true");
  expect(await page.evaluate(() => document.activeElement?.tagName)).not.toBe("INPUT");
  await page.setViewportSize({width: 1440, height: 900});
  await expect(expand).toBeVisible();
  await expand.click();
  await page.reload();
  await expect(collapse).toBeVisible();
  expect(errors).toEqual([]);
});

for (const theme of ["light", "dark"] as const) test(`tracker design remains usable across desktop and touch layouts (${theme})`, async ({page, browser}, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await seedUiState(page, {sets: [], theme});
  await mockApi(page);
  await page.goto("/rvx?runs=run-1,run-2");
  await expect(page.locator(".chart-card").first().locator("canvas")).toBeVisible();
  const search = page.getByRole("searchbox", {name: "Search runs", exact: true});
  await expect(search).not.toBeFocused();
  await search.focus();
  await expect(search).toHaveCSS("border-top-width", "0px");
  await expect(search).toHaveCSS("background-color", "rgba(0, 0, 0, 0)");
  await expect(search).toHaveCSS("box-shadow", "none");
  const status = page.getByRole("combobox", {name: "Status", exact: true});
  await expect(status).toHaveCSS("background-image", "none");
  await expect(status.locator("svg")).toHaveCount(1);
  const panel = page.locator(".runs-panel");
  const chart = page.locator(".chart-card").first();
  const panelStyle = await panel.evaluate(element => {
    const style = getComputedStyle(element);
    return {radius: style.borderRadius, surface: style.backgroundColor};
  });
  expect(parseFloat(panelStyle.radius)).toBeCloseTo(10.8, 0);
  expect(await chart.evaluate(element => getComputedStyle(element).borderRadius)).toBe(panelStyle.radius);
  expect(await chart.evaluate(element => getComputedStyle(element).backgroundColor)).toBe(panelStyle.surface);
  await page.mouse.move(1435, 895);
  await expect(chart.locator(".panel-actions")).toHaveCSS("opacity", "0");
  await chart.hover();
  await expect(chart.locator(".panel-actions")).toHaveCSS("opacity", "1");
  await chart.getByRole("button", {name: "Chart settings", exact: true}).click();
  const settings = page.getByRole("dialog", {name: "Edit chart", exact: true});
  await expect(settings).toBeVisible();
  await expect(settings).toBeFocused();
  await expect(settings.getByRole("searchbox")).not.toBeFocused();
  await expect(page.locator('[data-slot="dialog-overlay"]')).toHaveCSS("backdrop-filter", "none");
  await settings.getByRole("button", {name: "Cancel", exact: true}).click();
  await setTheme(page, theme === "light" ? "dark" : "light");
  await expect(page.locator("html")).toHaveAttribute("data-theme", theme === "light" ? "dark" : "light");
  await setTheme(page, theme);
  await page.screenshot({path: testInfo.outputPath(`canvas-${theme}-desktop.png`)});
  await page.getByRole("button", {name: "Collapse Runs panel", exact: true}).click();
  await expect(page.locator(".runs-dock")).toHaveCSS("width", "64px");
  await page.screenshot({path: testInfo.outputPath(`canvas-${theme}-rail.png`)});
  const touch = await browser.newContext({viewport: {width: 390, height: 844}, hasTouch: true});
  try {
    const mobile = await touch.newPage();
    mobile.on("pageerror", error => errors.push(error.message));
    await seedUiState(mobile, {sets: [], theme});
    await mockApi(mobile);
    await mobile.goto(new URL("/rvx?runs=run-1,run-2", page.url()).href);
    await expect(mobile.locator(".chart-card").first().locator("canvas")).toBeVisible();
    await expect(mobile.getByRole("searchbox", {name: "Search runs"})).not.toBeVisible();
    const dock = mobile.locator(".runs-dock");
    const box = (await dock.boundingBox())!;
    expect(box.x).toBeGreaterThanOrEqual(16);
    expect(390 - box.x - box.width).toBeGreaterThanOrEqual(16);
    expect(box.height).toBeLessThan(200);
    await mobile.screenshot({path: testInfo.outputPath(`canvas-${theme}-mobile.png`), fullPage: true});
    await mobile.getByRole("checkbox", {name: "Select grpo · baseline", exact: true}).uncheck();
    await expect(mobile).toHaveURL(/runs=run-1(?:&|$)/);
    await mobile.getByRole("button", {name: "Manage runs", exact: true}).click();
    await mobile.getByRole("button", {name: "Run details for grpo · warm-start", exact: true}).click();
    await expect(mobile.getByRole("dialog", {name: "Run details", exact: true})).toBeVisible();
    await mobile.keyboard.press("Escape");
    await mobile.screenshot({path: testInfo.outputPath(`canvas-${theme}-mobile-management.png`), fullPage: true});
    expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally {
    await touch.close();
  }
  expect(errors).toEqual([]);
});

